-- Ejecuta este script en el SQL Editor de Supabase.

CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres VARCHAR(80) NOT NULL,
  apellidos VARCHAR(80) NOT NULL,
  email VARCHAR(254) NOT NULL,
  celular VARCHAR(30) NOT NULL,
  nacimiento DATE NOT NULL,
  ciudad VARCHAR(100) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_clientes_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_clientes_celular ON clientes (celular);

CREATE TABLE IF NOT EXISTS reservas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes (id),
  email_reserva VARCHAR(254) NOT NULL,
  celular_reserva VARCHAR(30) NOT NULL,
  fecha DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  recorrido VARCHAR(20) NOT NULL CHECK (recorrido IN ('cienagas', 'magdalena', 'completa')),
  personas SMALLINT NOT NULL CHECK (personas BETWEEN 1 AND 12),
  nivel VARCHAR(20) NOT NULL CHECK (nivel IN ('ninguna', 'basica', 'avanzada')),
  chaleco BOOLEAN NOT NULL DEFAULT FALSE,
  almuerzo BOOLEAN NOT NULL DEFAULT FALSE,
  fotos BOOLEAN NOT NULL DEFAULT FALSE,
  comentarios VARCHAR(1000),
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'confirmada', 'cancelada')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_cliente_fecha UNIQUE (cliente_id, fecha),
  CONSTRAINT uq_email_fecha UNIQUE (email_reserva, fecha),
  CONSTRAINT uq_celular_fecha UNIQUE (celular_reserva, fecha),
  CONSTRAINT chk_reservas_hora CHECK (hora_fin > hora_inicio)
);

CREATE INDEX IF NOT EXISTS idx_reservas_horario ON reservas (fecha, hora_inicio, hora_fin, estado);

CREATE TABLE IF NOT EXISTS administradores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_administradores_email UNIQUE (email)
);

CREATE OR REPLACE FUNCTION set_actualizado_en() RETURNS trigger AS $$
BEGIN
  NEW.actualizado_en = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_clientes_actualizado ON clientes;
CREATE TRIGGER trg_clientes_actualizado
  BEFORE UPDATE ON clientes
  FOR EACH ROW
  EXECUTE FUNCTION set_actualizado_en();
